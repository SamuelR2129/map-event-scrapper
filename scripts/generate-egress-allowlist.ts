const ENV_URL_KEYS = ["GOOGLE_PLACES_URL", "GOOGLE_GEOCODE_URL", "PRODUCTION_DB_URL"];

export const deriveEnvHosts = (getenv: (key: string) => string | undefined): string[] => {
  const hosts: string[] = [];
  for (const key of ENV_URL_KEYS) {
    const raw = getenv(key);
    if (!raw) continue;
    try {
      const hostname = new URL(raw).hostname;
      if (hostname) hosts.push(hostname);
    } catch {
      // Ignore unparsable env values; manual hosts go in the static list.
    }
  }
  return hosts;
};

export const generateAllowlist = (envHosts: string[], staticHosts: string[] = STATIC_HOSTS): string[] => {
  const rules = new Set(staticHosts.map((h) => h.trim().toLowerCase()).filter(Boolean));

  for (const host of envHosts) {
    const lower = host.toLowerCase();
    const covered = [...rules].some((rule) => {
      if (rule.startsWith("*.")) {
        const base = rule.slice(2);
        return lower === base || lower.endsWith("." + base);
      }
      return rule === lower;
    });
    if (!covered) rules.add(lower);
  }

  return [...rules].sort();
};

export const formatAllowlist = (rules: string[]): string => {
  const header = [
    "# Egress allowlist for the scraper container (generated by scripts/generate-egress-allowlist.ts)",
    `# Generated: ${new Date().toISOString()}`,
    "# Format: exact host per line; '*.domain' matches domain and all subdomains.",
    "# Re-run `npm run generate-allowlist` after changing scraper targets or env URL hosts.",
  ];
  return [...header, ...rules, ""].join("\n");
};

if (require.main === module) {
  const outPath = path.resolve(process.cwd(), "docker", "egress-allowlist.txt");
  const envHosts = deriveEnvHosts((key) => process.env[key]);
  const rules = generateAllowlist(envHosts);
  const output = formatAllowlist(rules);
  writeFileSync(outPath, output);

  console.log(`Wrote ${rules.length} rules to ${outPath}`);
  for (const rule of rules) console.log(`  ${rule}`);
  console.log(`Env-derived hosts: ${envHosts.length ? envHosts.join(", ") : "(none found)"}`);
}

export const readAllowlistFile = (file: string): string[] => {
  const text = readFileSync(file, "utf-8");
  return parseRuleLines(text);
};

export function parseRuleLines(text: string): string[] {
  return text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
}